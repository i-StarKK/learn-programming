#include <stdio.h>   /* للطباعة والإدخال: printf, fgets */
#include <stdlib.h>  /* للذاكرة: malloc, free */
#include <string.h>  /* للنصوص: strlen, strncpy, strcmp */

/* struct: تجمع أكثر من متغير تحت اسم واحد */
struct Student {
    char name[50];
    int age;
    float grade;
};

/* لازم تعلن عن الدالة قبل ما تستخدمها (أو تكتبها فوق main) */
int add(int a, int b);
void print_student(const struct Student *s);
void double_value(int *value);

int main(void)
{
    /* ╭──────────────────────────────────────────────────────────────╮
     * │  01  ▸  المتغيرات والأنواع
     * ╰──────────────────────────────────────────────────────────────╯ */
    int age = 20;          /* رقم صحيح */
    float price = 9.99f;   /* رقم عشري (f في الآخر) */
    double big = 3.14159;  /* رقم عشري أدق */
    char letter = 'A';     /* حرف واحد */
    char name[50] = "Ahmed"; /* النص في C = مصفوفة حروف */

    /* ⚠️ المتغير المحلي (داخل دالة) بدون قيمة أولية فيه "زبالة" عشوائية، دايم عطه قيمة
     * (المتغيرات global و static تبدأ صفر تلقائي) */
    int total = 0;

    /* ╭──────────────────────────────────────────────────────────────╮
     * │  02  ▸  الطباعة
     * ╰──────────────────────────────────────────────────────────────╯ */
    /* %d رقم صحيح | %f عشري | %s نص | %c حرف | \n سطر جديد */
    printf("Name: %s, Age: %d\n", name, age);
    printf("Price: %.2f, Letter: %c\n", price, letter);
    printf("Big: %f\n", big);

    /* ╭──────────────────────────────────────────────────────────────╮
     * │  03  ▸  الشروط
     * ╰──────────────────────────────────────────────────────────────╯ */
    if (age >= 18) {
        printf("Adult\n");
    } else {
        printf("Minor\n");
    }

    /* ⚠️ غلط قاتل: if (age = 18) بدل if (age == 18)
     * = تعطي قيمة، و == تقارن.
     * الأولى تغير age لـ 18، والشرط يصير صح لأن أي رقم غير الصفر = true */

    /* ╭──────────────────────────────────────────────────────────────╮
     * │  04  ▸  التكرار
     * ╰──────────────────────────────────────────────────────────────╯ */
    for (int i = 0; i < 5; i++) {
        total += i;
    }
    printf("Total: %d\n", total);

    /* ╭──────────────────────────────────────────────────────────────╮
     * │  05  ▸  المصفوفات
     * ╰──────────────────────────────────────────────────────────────╯ */
    int numbers[5] = {10, 20, 30, 40, 50};
    int size = sizeof(numbers) / sizeof(numbers[0]); /* طريقة تحسب عدد العناصر
     * ⚠️ تشتغل بس على المصفوفة نفسها، مو لو مررتها لدالة لأنها تصير مؤشر */

    for (int i = 0; i < size; i++) {
        printf("numbers[%d] = %d\n", i, numbers[i]);
    }

    /* ⚠️ المصفوفة حجمها 5 = العناصر من [0] إلى [4]
     * numbers[5] برا الحدود! C ما بتمنعك وبتقرا ذاكرة مو لك */

    /* ╭──────────────────────────────────────────────────────────────╮
     * │  06  ▸  المؤشرات (Pointers) - أهم وأصعب شيء في C
     * ╰──────────────────────────────────────────────────────────────╯ */
    /* المؤشر = متغير يحفظ "عنوان" متغير ثاني في الذاكرة
     *   &x   = عنوان x
     *   *ptr = القيمة اللي في العنوان */
    /*
     *        x                        ptr
     *   ┌──────────┐             ┌──────────┐
     *   │    10    │ ◄────────── │  0x7ff4  │
     *   └──────────┘             └──────────┘
     *   address: 0x7ff4          يحفظ عنوان x
     *
     *   ptr   = 0x7ff4  (العنوان)
     *   *ptr  = 10      (اللي داخل العنوان)
     *   &x    = 0x7ff4
     */
    int x = 10;
    int *ptr = &x;

    printf("x = %d\n", x);
    printf("address of x = %p\n", (void *)ptr);
    printf("value via ptr = %d\n", *ptr);

    *ptr = 99; /* غيرنا x عن طريق المؤشر */
    printf("x now = %d\n", x);

    /* تمرير بالمؤشر عشان الدالة تعدل على المتغير الأصلي */
    int score = 5;
    double_value(&score);
    printf("score after double = %d\n", score);

    /* ╭──────────────────────────────────────────────────────────────╮
     * │  07  ▸  الذاكرة الديناميكية (malloc / free)
     * ╰──────────────────────────────────────────────────────────────╯ */
    int count = 5;
    int *arr = malloc(count * sizeof(int)); /* احجز مكان لـ 5 أرقام */

    /* ⚠️ دايم تأكد إن الحجز نجح */
    if (arr == NULL) {
        printf("Memory allocation failed\n");
        return 1;
    }

    for (int i = 0; i < count; i++) {
        arr[i] = i * i;
    }
    printf("arr[4] = %d\n", arr[4]);

    /* ⚠️ لازم تحرر كل شيء حجزته، وإلا صار تسريب ذاكرة (Memory Leak) */
    free(arr);
    /* ⚠️ بعد free خله NULL عشان ما تستخدمه بالغلط (Use After Free) */
    arr = NULL;

    /* ╭──────────────────────────────────────────────────────────────╮
     * │  08  ▸  النصوص
     * ╰──────────────────────────────────────────────────────────────╯ */
    char first[20] = "Hello";
    char copy[20];

    /* ⚠️ strcpy خطيرة لأنها ما تشيك على الحجم
     * استخدم strncpy وحط \0 بالآخر بنفسك */
    strncpy(copy, first, sizeof(copy) - 1);
    copy[sizeof(copy) - 1] = '\0';

    printf("copy = %s, length = %zu\n", copy, strlen(copy));

    /* ⚠️ لا تقارن النصوص بـ == ، استخدم strcmp (ترجع 0 لو متطابقة) */
    if (strcmp(first, copy) == 0) {
        printf("Strings are equal\n");
    }

    /* snprintf: أأمن طريقة تركب فيها نص */
    char greeting[50];
    snprintf(greeting, sizeof(greeting), "Hi %s, age %d", name, age);
    printf("%s\n", greeting);

    /* ╭──────────────────────────────────────────────────────────────╮
     * │  09  ▸  struct
     * ╰──────────────────────────────────────────────────────────────╯ */
    struct Student s;
    strncpy(s.name, "Sara", sizeof(s.name) - 1);
    s.name[sizeof(s.name) - 1] = '\0';
    s.age = 22;
    s.grade = 95.5f;
    print_student(&s);

    /* ╭──────────────────────────────────────────────────────────────╮
     * │  10  ▸  الإدخال من المستخدم
     * ╰──────────────────────────────────────────────────────────────╯ */
    /* ⚠️ لا تستخدم gets() أبدًا! انحذفت من اللغة لأنها ثغرة
     * استخدم fgets وحدد الحجم */
    char input[100];
    printf("Type something: ");
    if (fgets(input, sizeof(input), stdin) != NULL) {
        input[strcspn(input, "\n")] = '\0'; /* نشيل السطر الجديد من الآخر */
        printf("You typed: %s\n", input);
    }

    printf("add(3, 4) = %d\n", add(3, 4));

    return 0; /* 0 = البرنامج خلص بنجاح */
}

int add(int a, int b)
{
    return a + b;
}

/* const هنا يعني الدالة تقرا بس وما تعدل */
void print_student(const struct Student *s)
{
    /* -> تستخدمها مع المؤشر بدل . */
    printf("Student: %s, Age: %d, Grade: %.1f\n", s->name, s->age, s->grade);
}

void double_value(int *value)
{
    *value = *value * 2;
}

